import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
const course = process.argv[2];
const t = new StdioClientTransport({ command: process.execPath, args: ['dist/server.mjs'], env: { ...process.env, CHALK_COURSE_DIR: course, CHALK_NO_OPEN: '1', CHALK_PORT: '4790', CHALK_HOME: course + '/../..' }, stderr: 'inherit' });
const c = new Client({ name: 'smoke', version: '0' }, { capabilities: {} });
const notes = [];
c.fallbackNotificationHandler = async (n) => { notes.push(n); };
await c.connect(t);
console.log('caps', JSON.stringify(c.getServerCapabilities()));
const { tools } = await c.listTools();
console.log('tools', tools.length, tools.map(t => t.name).join(','));
console.log('schema size', JSON.stringify(tools).length);
await new Promise(r => setTimeout(r, 2500));
console.log('notifications', JSON.stringify(notes).slice(0, 300));
const call = async (name, args) => { const r = await c.callTool({ name, arguments: args }); console.log(name, '→', r.isError ? 'ERR ' : '', r.content.map(x => x.text ?? x.type).join(' | ').slice(0, 300)); return r; };
await call('lesson_ack', {});
await call('lesson_start', { topicId: 'pdas', mode: 'lecture' });
await call('board_run', { steps: [{ add: { id: 'a', kind: 'box', text: 'Wallet', at: [1, 1] } }, { add: { id: 'b', kind: 'box', text: 'PDA', at: [4, 1] } }, { add: { id: 'e', kind: 'arrow', from: 'a', to: 'b' } }, { say: 'hi' }] });
await call('board_run', { steps: [{ add: { id: 'x', kind: 'blob' } }] });
await call('board_state', {});
await call('check_ask', { question: { type: 'mcq', prompt: 'Q?', options: ['a', 'b'], answer: 1 } });
await call('quiz_create', { title: 'T', topic: 'pdas', questions: [{ type: 'mcq', prompt: 'x', options: ['a','b'], answer: 5 }] });
await call('cards_propose', { cards: [{ front: 'The {{c1::bump}} is 255 first' }, { front: 'Q', back: 'A' }] });
await call('syllabus_update', { ops: [{ op: 'add', title: 'Rent', after: 'accounts' }] });
await call('progress_update', { topicId: 'pdas', delta: 0.2, misconception: 'thinks PDAs have keys', reason: 'test' });
await call('progress_get', {});
await call('kb_search', { query: 'bump' });
await call('lesson_yield', { prompt: 'next?' });
await c.close();
process.exit(0);
