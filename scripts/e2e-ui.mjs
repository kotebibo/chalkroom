// Drives the UI against a running mock server: node scripts/e2e-ui.mjs <url> <outdir>
import { chromium } from 'playwright-core';
const [url = 'http://127.0.0.1:4800', out = '.'] = process.argv.slice(2);
const browser = await chromium.launch({ channel: process.env.PW_CHANNEL ?? 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(`${m.type()}: ${m.text()}`); });
page.on('pageerror', (e) => errors.push(`pageerror: ${e.message}`));
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` });
const step = async (name, fn) => { try { await fn(); console.log('ok  ', name); } catch (e) { console.log('FAIL', name, e.message.split('\n')[0]); await shot(`fail-${name.replace(/\W+/g, '-')}`); } };

await page.goto(url);
await step('gate', () => page.getByRole('button', { name: 'Text only' }).click());
await step('connected', () => page.getByText('Tutor connected').waitFor({ timeout: 8000 }));
await shot('01-start');
await step('open topic', () => page.getByRole('button', { name: /Program Derived Addresses/ }).click());
await step('start lesson', () => page.getByRole('button', { name: /Start lesson|Continue lesson/ }).click());
await step('check card', () => page.getByRole('dialog', { name: 'Check question' }).waitFor({ timeout: 30000 }));
await page.waitForTimeout(1500);
await shot('02-lesson');
await step('answer check', async () => { await page.getByRole('radio', { name: /Only the program/ }).click(); await page.getByRole('button', { name: 'Check' }).click(); });
await page.waitForTimeout(2500);
await shot('03-checked');
await step('ask question', async () => { await page.getByLabel('Ask a question').fill('Why no private key?'); await page.getByRole('button', { name: 'Ask', exact: true }).click(); });
await page.waitForTimeout(3000);
await step('next 1', () => page.getByRole('button', { name: 'Next', exact: true }).click());
await page.waitForTimeout(9000);
await shot('04-segment2');
await step('next 2', () => page.getByRole('button', { name: 'Next', exact: true }).click());
await step('quiz opens', () => page.getByText('PDAs — quick quiz').first().waitFor({ timeout: 30000 }));
await page.waitForTimeout(3000);
await shot('05-mermaid-quiz');
await step('take quiz', async () => {
  await page.getByRole('radio', { name: /off the ed25519/ }).click();
  await page.getByRole('button', { name: 'False' }).click();
  await page.getByPlaceholder('Why?').fill('There is no private key because it is off curve');
  await page.getByPlaceholder('Number').fill('255');
  await page.getByPlaceholder('Your answer').fill('_signed');
  await page.getByRole('button', { name: 'Keep this order' }).click();
  await page.getByPlaceholder('Explain in your own words…').fill('The PDA is off curve so there is no key; the program signs with invoke_signed.');
  await page.getByRole('button', { name: 'Submit' }).click();
});
await page.waitForTimeout(3000);
await shot('06-quiz-results');
await step('select shape', async () => { await page.locator('#chalk-board [data-id="seq"], #chalk-board .shape').first().click(); });
await step('cards tab', async () => { await page.getByRole('tab', { name: /Cards/ }).click(); await page.getByRole('button', { name: 'Cards from this lesson' }).click(); await page.getByText('Proposed by your tutor').waitFor({ timeout: 10000 }); await page.getByRole('button', { name: 'Accept all' }).click(); });
await page.waitForTimeout(800);
await shot('07-cards');
await step('review', async () => { await page.getByRole('button', { name: /^Review/ }).first().click(); await page.getByRole('button', { name: /Show answer/ }).click(); await page.getByRole('button', { name: /Good/ }).click(); });
await shot('08-review');
await step('progress', async () => { await page.getByRole('button', { name: 'Progress' }).click(); await page.getByText('Knowledge map').waitFor(); });
await page.waitForTimeout(800);
await shot('09-progress');
await step('replay', async () => { await page.getByRole('button', { name: '▶ Replay' }).first().click(); await page.getByRole('button', { name: /Play/ }).click(); });
await page.waitForTimeout(4000);
await shot('10-replay');
await step('close replay', () => page.getByRole('button', { name: 'Close' }).click());
await step('resources', async () => {
  await page.getByRole('button', { name: 'Resources' }).click();
  await page.locator('input[type=file]').setInputFiles(process.env.RES_FILE);
  await page.getByText(/sections · id/).first().waitFor({ timeout: 15000 });
});
await page.waitForTimeout(2500);
await shot('11-resources');
await step('home', async () => { await page.getByRole('button', { name: 'Home' }).click(); await page.getByText('Library').waitFor(); });
await shot('12-home');
await step('settings whiteboard', async () => { await page.getByRole('button', { name: 'Settings' }).click(); await page.getByRole('button', { name: 'Whiteboard' }).click(); await page.getByRole('button', { name: 'Classroom' }).click(); });
await page.waitForTimeout(800);
await shot('13-whiteboard');
console.log('\nconsole errors:', errors.length ? '\n' + [...new Set(errors)].slice(0, 30).join('\n') : 'none');
await browser.close();
